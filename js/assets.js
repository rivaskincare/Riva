/* =====================================================================
   RIVA asset finder — no file paths needed anywhere.
   Looks up images/videos by FILE NAME, wherever they live in the repo:
     1. assets-manifest.json (written automatically on every deploy)
     2. fallback: tries  assets/<name>.<ext>  directly (works without the Action)
   Names are case-insensitive; spaces/underscores count as hyphens.
   ===================================================================== */
(function () {
  "use strict";
  var IMG = ["webp", "avif", "jpg", "jpeg", "png", "gif", "svg"];
  var VID = ["mp4", "webm"];
  var PROBE_IMG = ["webp", "jpg", "jpeg", "png"];
  var index = {};      // normalised name -> [{ext, path}]
  var trusted = false; // true when the manifest was generated by the deploy Action

  var norm = function (s) { return s.toLowerCase().replace(/[\s_]+/g, "-"); };
  var enc = function (p) { return p.split("/").map(encodeURIComponent).join("/"); };
  function add(path) {
    var f = path.split("/").pop(), i = f.lastIndexOf(".");
    if (i < 1) return;
    var k = norm(f.slice(0, i));
    (index[k] = index[k] || []).push({ ext: f.slice(i + 1).toLowerCase(), path: path });
  }
  function lookup(stem, exts) {
    var l = index[stem]; if (!l) return null;
    for (var i = 0; i < exts.length; i++)
      for (var j = 0; j < l.length; j++) if (l[j].ext === exts[i]) return enc(l[j].path);
    return null;
  }
  function probe(url, video) {
    if (video && location.protocol !== "file:")  // HEAD request: lighter than loading the video
      return fetch(url, { method: "HEAD" }).then(function (r) { return r.ok ? url : null; }, function () { return null; });
    return new Promise(function (res) {
      var el = video ? document.createElement("video") : new Image();
      el.onload = el.onloadedmetadata = function () { res(url); };
      el.onerror = function () { res(null); };
      if (video) el.preload = "metadata";
      el.src = url;
    });
  }
  async function find(stem, kind) {
    var exts = kind === "video" ? VID : IMG;
    var hit = lookup(stem, exts);
    if (hit || trusted) return hit;
    var list = kind === "video" ? VID : PROBE_IMG;
    var res = await Promise.all(list.map(function (e) { return probe("assets/" + stem + "." + e, kind === "video"); }));
    for (var i = 0; i < res.length; i++) if (res[i]) return res[i];
    return null;
  }
  // product photos:  id, id-2, id-3 …  (any folder, any order)
  async function gallery(id) {
    var out = [], max = 0, k, nm = function (n) { return n === 1 ? id : id + "-" + n; };
    var re = new RegExp("^" + id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "(?:-(\\d+))?$");
    for (k in index) { var m = re.exec(k); if (m) { var n = m[1] ? +m[1] : 1; if (n > max) max = n; } }
    for (var i = 1; i <= max; i++) { var u = await find(nm(i)); if (u) out.push(u); }
    if (!trusted) { // simple mode (no deploy Action): keep looking for the next numbered file
      for (var j = max + 1; j <= max + 12; j++) { var v = await find(nm(j)); if (!v) break; out.push(v); }
    }
    return out;
  }

  var ready = (async function () {
    try {
      var r = await fetch("assets-manifest.json", { cache: "no-cache" });
      if (r.ok) {
        var m = await r.json();
        (m.files || []).forEach(add);
        trusted = m.generatedBy === "action";
      }
    } catch (e) { /* opened as a local file or no manifest yet: simple mode */ }

    var keys = {
      logo: "logo", logoMark: "logo-mark", logoFooter: "logo-footer",
      logoHero: "logo-hero", logoLockup: "logo-lockup",
      hero: "hero", about: "about", videoPoster: "video-poster"
    };
    var A = {}, names = Object.keys(keys);
    var found = await Promise.all(names.map(function (n) { return find(keys[n]); }));
    names.forEach(function (n, i) { A[n] = found[i]; });
    A.video = await find("video", "video");
    window.A = A;

    if (typeof PRODUCTS !== "undefined") {
      var gs = await Promise.all(PRODUCTS.map(function (p) { return gallery(norm(p.id)); }));
      PRODUCTS.forEach(function (p, i) { p.images = gs[i]; p.image = gs[i][0] || null; });
    }
  })();

  // load the site code after assets are known (classic scripts → same globals)
  ready.then(function () {
    ["js/app.js", "js/chat.js"].forEach(function (src) {
      var s = document.createElement("script"); s.src = src; s.async = false; document.body.appendChild(s);
    });
  });
  window.RIVA = { ready: ready };
})();
